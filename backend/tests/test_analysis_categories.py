@pytest.mark.parametrize(("language", "text", "expected"), CATEGORY_EXAMPLES, ids=[f"{index:02d}-{language}" for index, (language, _, _) in enumerate(CATEGORY_EXAMPLES, 1)])
def test_independent_category_examples_in_russian_and_kazakh(language, text, expected):
    from app.ai.engine import analyze

    record = {
        "id": "category-example", "source": "Синтетический контроль", "source_record_id": "CAT-001",
        "date": "2026-09-01", "text": text, "address": "неизвестно",
        "language": language, "privacy_status": "clear", "version": 1,
    }
    result = analyze([record], mode="tfidf")["results"][0]
    assert result["status"] != "blocked"
    assert result["category"] == expected, {"language": language, "text": text, "expected": expected, "actual": result["category"]}
    assert result["proposed_category"] == expected
